"""Export compiled harnesses to various formats: JSON, YAML, Python agent code."""

import json
from pathlib import Path
from typing import Optional


def export_to_json(compiled_harness: dict, path: Optional[str] = None) -> str:
    """Export a compiled harness to JSON format.

    Args:
        compiled_harness: CompiledHarness as dict.
        path: Optional file path to write to.

    Returns:
        JSON string.
    """
    output = json.dumps(compiled_harness, indent=2)
    if path:
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        Path(path).write_text(output)
    return output


def export_to_yaml(compiled_harness: dict, path: Optional[str] = None) -> str:
    """Export a compiled harness to YAML format.

    Args:
        compiled_harness: CompiledHarness as dict.
        path: Optional file path to write to.

    Returns:
        YAML string.
    """
    try:
        import yaml
    except ImportError:
        # Fallback to manual YAML-like output
        return _manual_yaml(compiled_harness, path)

    output = yaml.dump(compiled_harness, default_flow_style=False, sort_keys=False)
    if path:
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        Path(path).write_text(output)
    return output


def _manual_yaml(compiled_harness: dict, path: Optional[str] = None) -> str:
    """Simple YAML serializer when pyyaml is not available."""
    lines = []
    for key, value in compiled_harness.items():
        if isinstance(value, list):
            lines.append(f"{key}:")
            for item in value:
                lines.append(f"  - {item}")
        elif isinstance(value, dict):
            lines.append(f"{key}:")
            for k, v in value.items():
                lines.append(f"  {k}: {v}")
        else:
            lines.append(f"{key}: {value}")
    output = "\n".join(lines)
    if path:
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        Path(path).write_text(output)
    return output


